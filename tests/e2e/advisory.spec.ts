import { test,expect } from "@playwright/test";

test("advisory landing, transformation and problem links work in both languages on mobile",async({page},info)=>{
  const errors:string[]=[];
  page.on("pageerror",error=>errors.push(error.message));
  await page.setViewportSize({width:390,height:850});
  await page.emulateMedia({reducedMotion:"reduce"});
  await page.goto("/en");
  await page.getByRole("button",{name:"Menu",exact:true}).click();
  await page.getByRole("navigation",{name:"Main"}).getByRole("link",{name:"Services",exact:true}).click();
  await page.getByRole("link",{name:"Explore process consulting"}).click();
  await expect(page.getByRole("heading",{level:1})).toContainText("Then improve it.");
  await page.getByRole("button",{name:"Show connected workflow"}).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("status")).toHaveText("Proposed future state");
  await expect(page.getByText("Shared data source")).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:info.outputPath("advisory-mobile.png")});
  await page.getByRole("button",{name:/Disconnected software/}).click();
  await expect(page.locator(".advisory-response").getByRole("link",{name:/Systems Integration/})).toBeVisible();
  await page.getByRole("button",{name:/Automate/}).click();
  await expect(page.getByText("Proceed to rollout when the pilot meets the agreed checks.")).toBeVisible();
  await expect(page.locator("#advisory-services a")).toHaveCount(6);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  await page.locator(".advisory-response").getByRole("link",{name:/Systems Integration/}).click();
  await expect(page).toHaveURL(/\/en\/consulting\/systems-integration$/);
  await page.getByRole("link",{name:"Switch to Romanian"}).click();
  await expect(page.getByRole("heading",{level:1})).toHaveText("Integrarea sistemelor și arhitectura fluxurilor");
  await page.getByRole("link",{name:"Discută despre acest serviciu"}).click();
  await expect(page.locator("select[name=service]")).toHaveValue("systems-integration");
  expect(errors).toEqual([]);
});

test("Romanian audit form prepares a draft and saves a test inquiry",async({page})=>{
  await page.goto("/ro/contact");
  await expect(page.locator("select[name=service]")).toHaveValue("process-audit");
  await expect(page.locator("select[name=engagement]")).toHaveValue("discovery");
  await page.getByLabel("Nume de contact").fill("Client Fictiv");
  await page.getByLabel("E-mail",{exact:true}).fill("consultatie-ro@example.invalid");
  await expect(page.getByLabel("Companie (opțional)",{exact:true})).toHaveValue("");
  await page.getByLabel("Ce proces vrei să analizăm?").fill("Vrem să analizăm aprobările & raportarea.");
  await expect(page.getByRole("link",{name:"+40 754 916 034"})).toHaveAttribute("href","tel:+40754916034");
  const draft=page.getByRole("link",{name:"Deschide ciorna de e-mail"});
  await expect(draft).toHaveAttribute("href",/^mailto:maximcazacu0501@gmail\.com\?/);
  const params=new URL((await draft.getAttribute("href"))!).searchParams;
  expect(params.get("subject")).toBe("Cerere de audit de proces blen.");
  expect(params.get("body")).toContain("Vrem să analizăm aprobările & raportarea.");
  expect(params.get("body")).toContain("consultatie-ro@example.invalid");
  await page.getByRole("button",{name:"Salvează cererea de audit de test"}).click();
  await expect(page.getByRole("heading",{name:"Cerere de audit de test salvată"})).toBeVisible();
});

